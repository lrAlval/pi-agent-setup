// Local patch for @narumitw/pi-plan-mode (installed bundle, NOT upstream).
// Re-run after every `npm update` / reinstall of the package:
//   node /home/aiden/.pi/agent/patches/fix-plan-mode.mjs
// Idempotent: exits 0 with "already patched" when markers are present.
// Fails loud (non-zero + which pattern missed) on version drift.
import { readFileSync, writeFileSync, copyFileSync, existsSync } from "node:fs";

const PKG = "/home/aiden/.pi/agent/npm/node_modules/@narumitw/pi-plan-mode";
const CHUNK = `${PKG}/dist/chunks/chunk-MJV6WNHK.ts`;
const INDEX = `${PKG}/dist/index.ts`;
const MARK = "pi-agent-setup patch v2: read-only"; // must not appear in STRIP_REDIRECTIONS

function replaceOnce(path, text, oldStr, newStr, label) {
  const count = text.split(oldStr).length - 1;
  if (count === 0) {
    if (text.includes(MARK)) return text; // already patched by an earlier run
    console.error(`MISS [${label}] in ${path}`);
    process.exitCode = 1;
    return text;
  }
  if (count > 1) {
    console.error(`AMBIGUOUS(${count}) [${label}] in ${path}`);
    process.exitCode = 1;
    return text;
  }
  return text.replace(oldStr, newStr);
}

function patchFile(path, edits) {
  let text = readFileSync(path, "utf8");
  if (text.includes(MARK)) {
    console.log(`skip ${path}: already patched`);
    return;
  }
  if (!existsSync(path + ".orig")) copyFileSync(path, path + ".orig");
  for (const [oldStr, newStr, label] of edits) text = replaceOnce(path, text, oldStr, newStr, label);
  if (process.exitCode) {
    console.error(`NOT WRITTEN: ${path}`);
    return;
  }
  text = text.replace(
    "// @generated by scripts/build-runtime.mjs; do not edit.",
    `// @generated by scripts/build-runtime.mjs; do not edit.\n/* ${MARK} command + glob + sed-range + stale-selection fixes. Re-run patches/fix-plan-mode.mjs after package updates. */`,
  );
  writeFileSync(path, text);
  console.log(`patched ${path}`);
}

// ---- chunk: redirect stripper (v1, with v2 /dev/null-only tightening) ----
// Fresh installs lack stripRedirections entirely; insert it ahead of
// splitShellSegments. Upgrades that already carry v1 keep their copy.
function ensureRedirectStripper() {
  let text = readFileSync(CHUNK, "utf8");
  if (text.includes("function stripRedirections(command)")) return;
  if (!existsSync(CHUNK + ".orig")) copyFileSync(CHUNK, CHUNK + ".orig");
  const anchor = `function splitShellSegments(command) {\n  const trimmed = command.trim();`;
  if ((text.split(anchor).length - 1) !== 1) {
    console.error("MISS [redirect-stripper-anchor] in " + CHUNK);
    process.exit(1);
  }
  text = text.replace(
    anchor,
    `${STRIP_REDIRECTIONS}\nfunction splitShellSegments(command) {\n  const pre = stripRedirections(command);\n  if (!pre || !pre.ok) return void 0;\n  const trimmed = pre.text.trim();`,
  );
  writeFileSync(CHUNK, text);
  console.log(`inserted redirect stripper into ${CHUNK}`);
}

const STRIP_REDIRECTIONS = `/* pi-agent-setup patch v1: strip shell redirections before policy checks.
 * Pi reinstalls npm packages on update, so re-run patches/fix-plan-mode.mjs
 * after @narumitw/pi-plan-mode updates. */
function stripRedirections(command) {
  var out = [];
  var n = command.length;
  var i = 0;
  var quote = null;
  var escaped = false;
  while (i < n) {
    var c = command.charAt(i);
    if (escaped) { out.push(c); escaped = false; i += 1; continue; }
    if (quote === "'") { out.push(c); if (c === "'") quote = null; i += 1; continue; }
    if (quote === '"') {
      out.push(c);
      if (c === "\\\\" && i + 1 < n) { out.push(command.charAt(i + 1)); i += 2; continue; }
      if (c === '"') quote = null;
      i += 1; continue;
    }
    if (c === "\\\\") { out.push(c); escaped = true; i += 1; continue; }
    if (c === "'" || c === '"') { quote = c; out.push(c); i += 1; continue; }
    var redir = c === "<" || c === ">" || (c === "&" && command.charAt(i + 1) === ">");
    if (!redir) { out.push(c); i += 1; continue; }
    var fdLen = 0;
    var j = i - 1;
    while (j >= 0 && command.charAt(j) >= "0" && command.charAt(j) <= "9") { fdLen += 1; j -= 1; }
    var before = j < 0 ? " " : command.charAt(j);
    if (!(fdLen > 0 && (before === " " || before === "\\t" || before === ";" || before === "|" || before === "&" || before === "("))) {
      fdLen = 0;
    }
    var spanStart = i - fdLen;
    var op = "";
    while (i < n && (command.charAt(i) === "<" || command.charAt(i) === ">" || command.charAt(i) === "&")) { op += command.charAt(i); i += 1; }
    if (i < n && command.charAt(i) === "-" && op.indexOf("&") !== -1) { op += "-"; i += 1; }
    if (op !== "<" && op !== ">" && op !== ">>" && op !== "<<" && op !== ">&" && op !== "<&" && op !== "<>" && op !== "&>" && op !== "&>>" && op !== ">&-" && op !== "<&-") {
      return { ok: false };
    }
    var k = i;
    while (k < n && (command.charAt(k) === " " || command.charAt(k) === "\\t")) k += 1;
    if (k >= n) return { ok: false };
    var target = "";
    var q = command.charAt(k);
    if (q === "'" || q === '"') {
      k += 1;
      var closed = false;
      var tEsc = false;
      while (k < n) {
        var t = command.charAt(k);
        if (tEsc) { target += t; tEsc = false; k += 1; continue; }
        if (q === '"' && t === "\\\\") { tEsc = true; k += 1; continue; }
        if (t === q) { closed = true; k += 1; break; }
        target += t; k += 1;
      }
      if (!closed) return { ok: false };
    } else {
      if (q === "(" || q === ")") return { ok: false };
      var s = k;
      while (k < n && " \\t;|&()<>'\\\"".indexOf(command.charAt(k)) === -1) k += 1;
      if (k === s) return { ok: false };
      target = command.slice(s, k);
      if (target.indexOf("(") !== -1 || target.indexOf(")") !== -1) return { ok: false };
    }
    if (target.length > 5 && target.slice(0, 5) === "/dev/" && target !== "/dev/null") return { ok: false };
    /* pi-agent-setup patch v2: only /dev/null file targets and fd dups/closes
     * may be stripped; "> file" stays blocked so output redirects cannot
     * smuggle writes through the read-only policy. */
    var isFdClose = op === ">&-" || op === "<&-";
    var isFdDup = op === ">&" || op === "<&";
    if (isFdDup && !/^[0-9]+$/.test(target)) return { ok: false };
    if (!isFdClose && !isFdDup && target !== "/dev/null") return { ok: false };
    out.length = spanStart;
    var spanLen = k - spanStart;
    for (var z = 0; z < spanLen; z += 1) out.push(" ");
    i = k;
  }
  if (quote !== null || escaped) return { ok: false };
  return { ok: true, text: out.join("") };
}`;

