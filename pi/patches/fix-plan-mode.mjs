function ensureRedirectStripper() {
  let text = readFileSync(CHUNK, "utf8");
  if (text.includes("function stripRedirections(command)")) return;
  if (!existsSync(CHUNK + ".orig")) copyFileSync(CHUNK, CHUNK + ".orig");
  const anchor = `function splitShellSegments(command) {\n  const trimmed = command.trim();`;
  if ((text.split(anchor).length - 1) !== 1) {
    console.error("MISS [redirect-stripper-anchor] in " + CHUNK);
    process.exit(1);
  }
  text = text.replace(
    anchor,
    `${STRIP_REDIRECTIONS}\nfunction splitShellSegments(command) {\n  const pre = stripRedirections(command);\n  if (!pre || !pre.ok) return void 0;\n  const trimmed = pre.text.trim();`,
  );
  writeFileSync(CHUNK, text);
  console.log(`inserted redirect stripper into ${CHUNK}`);
}

